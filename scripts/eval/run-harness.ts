// scripts/eval/run-harness.ts
// Generates the Arm A vs C run harness so Claude and GitHub Copilot sessions are consistent
// and their results drop straight into the observation log + AE provenance:
//   - runs/answer-key.md   : per-fixture prompt + the GOLD answer (fault id, evidence, stage)
//   - runs/scoring-sheet.csv: one blank row per client × arm × fixture × trial
//   - runs/transcripts/    : where each session's transcript is saved (provenance)
// Pure formatters (categoryOf/trialsFor/nlExpectation/promptFor/goldFor/build*) are unit-tested;
// runMain() does the I/O by running the SHIPPED diagnosis core to derive each gold answer.
import * as fs from 'fs';
import * as path from 'path';
import { parseTritonCfg } from '../../src/services/tritonCfg';
import { diagnoseTritonDeck, Finding, Expectations } from '../../src/services/diagnostics';
import { resolveCfg, fsProbe } from '../../src/mcp/tools/diagnoseProject';
import { ManifestEntry } from '../../src/services/diagnoseCorpusScore';

export type Category = 'deck-fault' | 'expectation' | 'clean';

export interface Gold {
  dir: string;
  category: Category;
  prompt: string;
  expectationText: string; // the NL expectation clause (or ''), so an isolated runner can rebuild the prompt with a temp path
  goldFinding: string;   // expected finding id, or 'clean'
  goldEvidence: string;  // evidence string of the matching finding (or '')
  goldStage: string;     // the tool's 'look at' pointer = the right artifact/stage (or '')
}

export function categoryOf(entry: ManifestEntry): Category {
  if (entry.expect === 'clean') return 'clean';
  if (entry.expect.startsWith('expectation-')) return 'expectation';
  return 'deck-fault';
}

/** Deck faults run multiple trials (agent stochasticity); expectation + clean are ×1. */
export function trialsFor(entry: ManifestEntry, deckTrials: number): number {
  return categoryOf(entry) === 'deck-fault' ? deckTrials : 1;
}

/** Turn a structured expectations object into a natural-language clause the agent can act on. */
export function nlExpectation(exp: Expectations | undefined): string {
  if (!exp) return '';
  const parts: string[] = [];
  if (exp.numRunoffs !== undefined) parts.push(`it should have ${exp.numRunoffs} runoff zones`);
  if (exp.numSources !== undefined) parts.push(`it should have ${exp.numSources} water sources`);
  if (exp.simDurationSec !== undefined) parts.push(`the simulation should run for ${exp.simDurationSec} seconds`);
  if (exp.forcingRange) parts.push(`the forcing should stay within ${exp.forcingRange.min}..${exp.forcingRange.max}`);
  if (exp.inputs && exp.inputs.length) parts.push(`these inputs should be present: ${exp.inputs.join(', ')}`);
  return parts.length ? ` I also expect that ${parts.join('; ')}.` : '';
}

export function promptFor(relDir: string, entry: ManifestEntry): string {
  // NEUTRAL prompt: does not presuppose breakage (a leading "it's broken" prompt primes the agent
  // to invent faults on a valid deck, invalidating the clean control). Matches scripts/eval/run-arm.sh.
  return `Review the TRITON project at \`${relDir}\` (relative to the repo root) for configuration or `
    + `input problems. If it is correctly set up, say so; otherwise name the fault and tell me where it is.`
    + nlExpectation(entry.expectations);
}

export function goldFor(findings: Finding[], entry: ManifestEntry): Pick<Gold, 'goldFinding' | 'goldEvidence' | 'goldStage'> {
  if (entry.expect === 'clean') {
    return { goldFinding: 'clean', goldEvidence: '', goldStage: 'none — deck is coherent; the agent must NOT invent a fault' };
  }
  const f = findings.find((x) => x.id === entry.expect);
  return f
    ? { goldFinding: f.id, goldEvidence: f.evidence, goldStage: f.pointsTo }
    : { goldFinding: entry.expect, goldEvidence: '(tool did not emit — check the fixture)', goldStage: '' };
}

