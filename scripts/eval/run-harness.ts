/** Machine-readable prompts + gold, for the automated runner + judge (never fed to the agent). */
export function buildPromptsJson(golds: Gold[]): string {
  return JSON.stringify(golds, null, 2) + '\n';
}

export function buildScoringCsv(entries: ManifestEntry[], clients: string[], arms: string[], deckTrials: number): string {
  const header = 'client,arm,fixture,category,trial,found_fault,right_stage,turns,false_claims,called_tool,notes';
  const rows: string[] = [header];
  for (const client of clients) {
    for (const arm of arms) {
      for (const entry of entries) {
        const n = trialsFor(entry, deckTrials);
        for (let t = 1; t <= n; t++) {
          // called_tool is only meaningful for Arm A (Arm C has no tool to call).
          rows.push([client, arm, entry.dir, categoryOf(entry), String(t), '', '', '', '', arm === 'A' ? '' : 'n/a', ''].join(','));
        }
      }
    }
  }
  return rows.join('\n') + '\n';
}

/** Strip the repo root from a path the tool resolved, leaving a repo-relative one.
 *
 *  `diagnoseTritonDeck` is handed an absolute deck directory here, so findings that name a
 *  file that does not exist (`missing-input-file`, `expectation-inputs-present`) carry an
 *  absolute path in their evidence. That is right in an editor and wrong in a tracked file:
 *  answer-key.md and prompts.json are committed, so regenerating them on another machine
 *  would rewrite two of the 32 fixtures with that machine's home directory. */
export function repoRelative(s: string, repoRoot: string): string {
  return s.split(`${repoRoot}${path.sep}`).join('');
}

export function runMain(): void {
  const repoRoot = path.resolve(__dirname, '../..');
  const corpus = path.join(__dirname, '../..', 'eval', 'diagnose-corpus');
  const manifest = JSON.parse(fs.readFileSync(path.join(corpus, 'manifest.json'), 'utf8'));
  const entries: ManifestEntry[] = manifest.fixtures;
  const deckTrials = Number(process.env.DECK_TRIALS ?? '3');
  const clients = ['claude', 'copilot'];
  const arms = ['A', 'C'];

  const golds: Gold[] = entries.map((entry) => {
    const dir = path.join(corpus, 'fixtures', entry.dir);
    const relDir = `eval/diagnose-corpus/fixtures/${entry.dir}`;
    const cfgAbs = resolveCfg(dir, entry.cfgPath ? path.resolve(dir, entry.cfgPath) : undefined);
    const findings = typeof cfgAbs === 'string'
      ? diagnoseTritonDeck(parseTritonCfg(fs.readFileSync(cfgAbs, 'utf8')), path.dirname(cfgAbs), fsProbe(), entry.expectations).findings
      : [];
    const gold = goldFor(findings, entry);
    return {
      dir: entry.dir, category: categoryOf(entry), prompt: promptFor(relDir, entry),
      expectationText: nlExpectation(entry.expectations),
      ...gold, goldEvidence: repoRelative(gold.goldEvidence, repoRoot),
    };
  });

  const runsDir = path.join(corpus, 'runs');
  fs.mkdirSync(path.join(runsDir, 'transcripts'), { recursive: true });
  fs.writeFileSync(path.join(runsDir, 'answer-key.md'), buildAnswerKey(golds));
  fs.writeFileSync(path.join(runsDir, 'scoring-sheet.csv'), buildScoringCsv(entries, clients, arms, deckTrials));
  fs.writeFileSync(path.join(runsDir, 'prompts.json'), buildPromptsJson(golds));

  const totalCells = clients.length * arms.length * entries.reduce((s, e) => s + trialsFor(e, deckTrials), 0);
  // eslint-disable-next-line no-console
  console.log(`Wrote runs/answer-key.md (${golds.length} fixtures) and runs/scoring-sheet.csv `
    + `(${totalCells} cells = ${clients.length} clients × ${arms.length} arms × [deck faults ×${deckTrials}, others ×1]).`);
}

if (require.main === module) runMain();
